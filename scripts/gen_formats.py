#!/usr/bin/env python3
"""Generate src/formats.rs from ConvertX converter properties.

Usage:
  git clone --depth 1 https://github.com/C4illin/ConvertX /tmp/convertx-src
  bun run scripts/dump_convertx_props.ts   # writes /tmp/convertx-props.json
  python3 scripts/gen_formats.py /tmp/convertx-props.json > src/formats.rs
"""
import json, sys

# Priority order as declared in ConvertX src/converters/main.ts.
ORDER = ["inkscape","libjxl","resvg","vips","libheif","xelatex","calibre","dasel",
         "libreoffice","pandoc","msgconvert","dvisvgm","imagemagick","graphicsmagick",
         "assimp","ffmpeg","potrace","vtracer","vcf","markitdown"]

props = json.load(open(sys.argv[1]))

def lit(xs):
    return "&[" + ", ".join('"%s"' % x for x in xs) + "]"

print("// GENERATED by scripts/gen_formats.py from ConvertX converter tables. Do not edit.")
print("// Source: https://github.com/C4illin/ConvertX (src/converters/*.ts)\n")
print("pub struct Group {\n    pub from: &'static [&'static str],\n    pub to: &'static [&'static str],\n}\n")
print("pub struct Converter {\n    pub name: &'static str,\n    pub groups: &'static [Group],\n}\n")
print("pub static CONVERTERS: &[Converter] = &[")
for name in ORDER:
    p = props[name]
    print("    Converter {")
    print('        name: "%s",' % name)
    print("        groups: &[")
    for key in p["from"]:
        fr = sorted(set(x.lower() for x in p["from"][key]))
        to = sorted(set(x.lower() for x in p["to"].get(key, [])))
        print("            Group {")
        print("                from: %s," % lit(fr))
        print("                to: %s," % lit(to))
        print("            },")
    print("        ],")
    print("    },")
print("];")
